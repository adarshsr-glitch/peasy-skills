import type { Scenario } from '../types';
import { Prototype } from './Prototype';

export const blankNewFeature: Scenario = {
  id: 'blank-new-feature',
  label: {
    nl: 'Nieuwe feature · Begin met een leeg canvas',
    en: 'New feature · Start from a blank canvas',
  },
  shortLabel: { nl: '+ Nieuwe feature', en: '+ New feature' },
  peasyUrl: 'https://peasy.be/',
  description: {
    nl: 'Schrijf zelf een briefing en loop door een generieke intake.',
    en: 'Write your own brief and walk through a generic intake.',
  },
  vagueBrief: { nl: '', en: '' },
  questions: [
    {
      id: 'surface',
      prompt: {
        nl: 'Op welke pagina of surface moet deze feature verschijnen?',
        en: 'Which page or surface should this feature live on?',
      },
    },
    {
      id: 'user-job',
      prompt: {
        nl: 'Wie is de gebruiker en wat probeert die te bereiken?',
        en: 'Who is the user and what are they trying to do?',
      },
    },
    {
      id: 'primary-action',
      prompt: {
        nl: 'Wat is de primaire actie — de ene tap of submit — en wat gebeurt er daarna?',
        en: 'What is the primary action — the one tap or submit — and what should happen after?',
      },
    },
    {
      id: 'constraints',
      prompt: {
        nl: 'Zijn er randvoorwaarden? Compliance, bestaande componenten, deadlines?',
        en: 'Any constraints? Compliance, existing components, deadlines?',
      },
    },
  ],
  Prototype,
  generateMarkdown(answers) {
    const surface = answers.surface ?? '[open]';
    const userJob = answers['user-job'] ?? '[open]';
    const primary = answers['primary-action'] ?? '[open]';
    const constraints = answers.constraints ?? '[open]';
    return [
      '# New feature · Draft ticket',
      '',
      '> ⚠️ Written from a free-form brief. Every field below reflects the PM\'s answers verbatim; a backend would restructure and enrich these before closing.',
      '',
      '## Summary',
      '',
      'A new Peasy feature described by the PM in Studio\'s blank intake.',
      '',
      '## Scope',
      '',
      '### In scope',
      '',
      `- Surface: ${surface}`,
      `- Primary action: ${primary}`,
      '',
      '## User stories',
      '',
      '- As the user described below, I want to achieve the stated goal so that I move closer to the primary action.',
      `  - User & job: ${userJob}`,
      '',
      '## Business rules',
      '',
      `- Constraints: ${constraints}`,
      '',
      '## Open questions',
      '',
      '- `[open]` — Full acceptance-criteria tree needs a sprint-planning conversation; this is a seed ticket.',
      '- `[open]` — Visual spec requires either a Figma link or a pack-driven prototype; neither available for a free-form brief.',
      '',
      '---',
      '',
      '_Generated by Peasy Studio. Review before pasting into Jira._',
    ].join('\n');
  },
};

// Compose a Jira-ready markdown spec from the brief + chat answers.
//
// REALITY CHECK: in production this logic lives in the peasy-requirements
// skill (`.claude/skills/peasy-requirements/SKILL.md`), which reads the
// pack directly and emits markdown. The sandbox stand-in is a hand-written
// composer so the UI can be demonstrated without a backend.

type Answers = {
  brief: string;
  user: string;
  surfaces: string;
  'change-shape': string;
  'jira-epic': string;
  'success-signal': string;
};

export function generateJiraMarkdown(answers: Answers): string {
  const epic = answers['jira-epic'].trim();
  const linksToANB1293 = /anb[-\s]?1293/i.test(epic);
  const unresolved = epic.toLowerCase().includes('open') || epic === '';

  const title = deriveTitle(answers.brief);
  const openItems = unresolved
    ? ['Jira epic not yet assigned.']
    : [];

  const sections: string[] = [];

  sections.push(`# ${title}`);
  sections.push('');
  sections.push('> ⚠️ Enriched from a brief; review `[open]` items before closing.');

  if (openItems.length) {
    sections.push('');
    sections.push('## ⚠️ Open items (resolve before merge)');
    sections.push('');
    openItems.forEach((item, i) => sections.push(`${i + 1}. ${item}`));
  }

  sections.push('');
  sections.push('## Summary');
  sections.push('');
  sections.push(answers.brief.trim());

  sections.push('');
  sections.push('## Scope');
  sections.push('');
  sections.push('### In scope');
  sections.push('');
  sections.push(`- Change shape: ${answers['change-shape'].trim()}`);
  sections.push(`- Affected surfaces: ${answers.surfaces.trim()}`);

  sections.push('');
  sections.push('### Out of scope');
  sections.push('');
  sections.push('- `[open]` — resolve with PM before implementation starts.');

  sections.push('');
  sections.push('## User stories');
  sections.push('');
  sections.push(`As a **${answers.user.trim()}**, I want the feature described above so that **${answers['success-signal'].trim()}**.`);

  sections.push('');
  sections.push('## Acceptance criteria');
  sections.push('');
  sections.push('```gherkin');
  sections.push(`Given the ${answers.user.trim()} is on the affected surface`);
  sections.push('When the feature is exercised per the brief above');
  sections.push(`Then the outcome described in the success signal is observable`);
  sections.push('```');

  sections.push('');
  sections.push('## Business rules');
  sections.push('');

  if (linksToANB1293) {
    sections.push('Rules below lifted verbatim from `pack/rules/anb-1293.md`:');
    sections.push('');
    sections.push('- All 17 specification fields are mandatory. `[ANB-1304 AC1]`');
    sections.push('- Product name must be unique per supplier (case-insensitive). `[ANB-1358 AC1]`');
    sections.push('- Status = Niet actief → `Toon in vergelijking` auto-set to Nee and locked. `[ANB-1306 AC5]`');
    sections.push('- Save actions appear at both top and bottom of the page. `[ANB-1305 AC1]`');
    sections.push('- Supplier is read-only during create and duplicate. `[ANB-1303 AC3, ANB-1347 AC4]`');
    sections.push('');
    sections.push('(Full list in `pack/rules/anb-1293.md`.)');
  } else {
    sections.push('- `[open]` — no rules pulled from the pack. Resolve with PM / FA before merge.');
  }

  sections.push('');
  sections.push('## Validation copy');
  sections.push('');

  if (linksToANB1293) {
    sections.push('Required-field message (lifted from `pack/terminology/validation.md`):');
    sections.push('');
    sections.push('| Lang | Message |');
    sections.push('| --- | --- |');
    sections.push('| NL | Dit veld is verplicht. |');
    sections.push('| FR | Ce champ est obligatoire. |');
    sections.push('| EN | This field is required. |');
  } else {
    sections.push('- `[open]` — validation copy not in pack. Request from Peasy.');
  }

  sections.push('');
  sections.push('## Open questions');
  sections.push('');
  if (openItems.length) {
    openItems.forEach((item) => sections.push(`- \`[open]\` — ${item}`));
  } else {
    sections.push('- None flagged in this session. Review the summary and user story for anything the brief left ambiguous.');
  }

  sections.push('');
  sections.push('## Dependencies');
  sections.push('');
  sections.push(`- Jira epic: ${epic || '`[open]`'}`);
  if (linksToANB1293) {
    sections.push(`- ANB-1045 — Supplier screen epic (per \`ANB-1293 Dependencies\`).`);
  }

  sections.push('');
  sections.push('---');
  sections.push('');
  sections.push('_Generated by Peasy Brainstorm (sandbox demo). Review every `[open]` before pasting into Jira._');

  return sections.join('\n');
}

function deriveTitle(brief: string): string {
  const trimmed = brief.trim().split('\n')[0]?.trim() ?? 'New feature';
  // Simple heuristic: take first sentence or first 60 chars.
  const firstSentence = trimmed.split(/[.!?]/)[0];
  const candidate = firstSentence.length > 0 ? firstSentence : trimmed;
  return candidate.length > 70 ? candidate.slice(0, 67) + '…' : candidate;
}
